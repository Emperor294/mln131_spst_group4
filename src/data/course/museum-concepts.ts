const museumConceptIndex = new Map<MuseumConceptId, MuseumConcept>(
  MUSEUM_CONCEPTS.map((concept) => [concept.id, concept]),
);

export function getMuseumConceptById(id: string) {
  return museumConceptIndex.get(id as MuseumConceptId);
}

export function getMuseumConceptsByChapterId(chapterId: ChapterId) {
  return MUSEUM_CONCEPTS.filter((concept) => concept.chapterId === chapterId);
}
