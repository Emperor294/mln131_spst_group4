import { getLessonTextbookSourceRefs } from "./lesson-page-map";
import type { ChapterId, LessonId, MuseumConcept, MuseumConceptId } from "./types";

function lessonRefs(...lessonIds: readonly LessonId[]) {
  const seen = new Set<string>();

  return lessonIds.flatMap((lessonId) => getLessonTextbookSourceRefs(lessonId)).filter((reference) => {
    if (seen.has(reference.id)) return false;
    seen.add(reference.id);
    return true;
  });
}

